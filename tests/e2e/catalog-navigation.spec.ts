import {test,expect} from "@playwright/test";
test("preview arrows and keyboard follow filtered catalog order and preserve the collection",async({page})=>{
 await page.goto("/"); await page.getByRole("button",{name:"Catalog"}).click();
 const d=page.getByRole("dialog");
 await d.getByRole("tab",{name:/^Spell/}).click();
 await d.getByRole("textbox",{name:"Search cards"}).fill("SP-0");
 await d.getByRole("button",{name:/Inspect SP-01/}).click();
 const nav=d.getByRole("navigation",{name:"Card preview navigation"});
 await expect(nav.getByRole("status")).toHaveText("1 / 9");
 await expect(nav.getByRole("button",{name:"Previous card"})).toBeDisabled();
 await nav.getByRole("button",{name:"Next card"}).click();
 await expect(d.locator(".game-card")).toHaveAttribute("aria-label","Drawn Curtain card");
 await expect(nav.getByRole("status")).toHaveText("2 / 9");
 await page.keyboard.press("ArrowRight"); await expect(d.locator(".game-card")).toHaveAttribute("aria-label","Crystal Skin card");
 await page.keyboard.press("ArrowLeft"); await expect(d.locator(".game-card")).toHaveAttribute("aria-label","Drawn Curtain card");
 for(let i=2;i<9;i++) await nav.getByRole("button",{name:"Next card"}).click();
 await expect(nav.getByRole("status")).toHaveText("9 / 9");
 await expect(nav.getByRole("button",{name:"Next card"})).toBeDisabled();
 await page.keyboard.press("ArrowRight"); await expect(nav.getByRole("status")).toHaveText("9 / 9");
 await nav.getByRole("button",{name:"Back to collection"}).click();
 await expect(d.getByRole("textbox",{name:"Search cards"})).toHaveValue("SP-0");
 await expect(d.getByRole("tab",{name:/^Spell/})).toHaveAttribute("aria-selected","true");
 await d.getByRole("textbox",{name:"Search cards"}).fill("SP-35");
 await d.getByRole("button",{name:/Inspect SP-35/}).click();
 await expect(nav.getByRole("button",{name:"Previous card"})).toBeDisabled();
 await expect(nav.getByRole("button",{name:"Next card"})).toBeDisabled();
 await nav.getByRole("button",{name:"Back to collection"}).click();
 await d.getByRole("textbox",{name:"Search cards"}).fill("");
 await d.getByRole("tab",{name:/^Item/}).click();
 await d.getByRole("button",{name:/Inspect IT-01/}).click();
 await page.setViewportSize({width:390,height:844});
 await nav.getByRole("button",{name:"Next card"}).click();
 await expect(d.locator(".game-card")).toHaveAttribute("aria-label","Adventurer's Satchel card");
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:"test-results/catalog-preview-mobile.png"});
 await page.keyboard.press("Escape"); await expect(d).not.toBeVisible();
});
