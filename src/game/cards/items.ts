import { z } from "zod";
export const itemEffectSchema = z.discriminatedUnion("op", [
  z.object({
    op: z.literal("CAPACITY"),
    slot: z.enum(["elements", "items", "mirrors", "relics"]),
    amount: z.number().int().positive(),
  }),
  z.object({
    op: z.literal("MOVEMENT"),
    amount: z.number().int().positive(),
    selectable: z.boolean().optional(),
  }),
  z.object({ op: z.literal("AETHER_WILD") }),
  z.object({
    op: z.literal("DOUBLE"),
    elements: z.array(z.enum(["Air", "Earth", "Fire", "Water", "Aether"])),
  }),
  z.object({
    op: z.literal("REWARD"),
    event: z.enum(["FRAGMENT", "COMPANION", "PAIR", "PERMANENT_SIGIL"]),
    amount: z.number().int().positive(),
  }),
  z.object({
    op: z.literal("ARRIVAL_EXTRA"),
    amount: z.number().int().positive(),
  }),
  z.object({
    op: z.literal("LEARNING_DISCOUNT"),
    amount: z.number().int().positive(),
  }),
  z.object({
    op: z.literal("TOOL"),
    action: z.enum([
      "ELEMENT",
      "MIRRORS",
      "ITEM",
      "SPELL",
      "SIGIL",
      "SECRET",
      "LEAVE_COMPANIONS",
      "OCCULDOR",
      "SACRIFICE_COMPANION",
    ]),
    reward: z.number().int().min(0),
    beforeMove: z.boolean().optional(),
  }),
  z.object({
    op: z.literal("REDUCE_PENALTY"),
    amount: z.number().int().positive(),
  }),
  z.object({ op: z.literal("IGNORE_PARALYSIS") }),
  z.object({ op: z.literal("FREE_FRAGMENT") }),
  z.object({ op: z.literal("IGNORE_CONFLICTS") }),
]);
export type ItemEffect = z.infer<typeof itemEffectSchema>;
const capacity = (
  slot: "elements" | "items" | "mirrors" | "relics",
  amount: number,
): ItemEffect => ({ op: "CAPACITY", slot, amount });
const reward = (
  event: "FRAGMENT" | "COMPANION" | "PAIR" | "PERMANENT_SIGIL",
  amount: number,
): ItemEffect => ({ op: "REWARD", event, amount });
const tool = (
  action: Extract<ItemEffect, { op: "TOOL" }>["action"],
  reward: number,
  beforeMove = false,
): ItemEffect => ({ op: "TOOL", action, reward, beforeMove });
