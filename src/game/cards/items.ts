export const items = rows.map(([name, timing, cost, effect, effects], i) => ({
  id: `IT-${String(i + 1).padStart(2, "0")}`,
  name,
  family: "Item" as const,
  subtype: i < 10 ? "Equipment" : i < 19 ? "Tool" : "Relic",
  timing,
  cost,
  effect,
  description: effect,
  requirements: cost,
  effects: effects.map((e) => itemEffectSchema.parse(e)),
  usageLimit: i >= 10 && i < 19 ? "PLAYER_ROUND" : "NONE",
  version: "0.3",
  status: "REVIEW",
}));
export const itemById = Object.fromEntries(items.map((c) => [c.id, c]));
